CREATE TABLE TEACHERS (
    TEACHER_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADDRESS VARCHAR(255),
    NAME VARCHAR(255),
    PHONE VARCHAR(50)
);

CREATE TABLE CLASSROOMS (
    CLASSROOM_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEACHER_ID BIGINT,
    NAME VARCHAR(255),
    FOREIGN KEY (TEACHER_ID) REFERENCES TEACHERS(TEACHER_ID)
);


CREATE TABLE STUDENTS (
    STUDENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLASSROOM_ID BIGINT,
    NAME VARCHAR(255),
    IS_ENROLLED BOOLEAN,
    FOREIGN KEY (CLASSROOM_ID) REFERENCES CLASSROOMS(CLASSROOM_ID)
);

CREATE TABLE ATTENDANCELISTS (
    ATTENDANCELIST_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CLASSROOM_ID BIGINT,
    ATTENDANCEDATE DATE,
    FOREIGN KEY (CLASSROOM_ID) REFERENCES CLASSROOMS(CLASSROOM_ID)
);

CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STUDENT_ID BIGINT,
    ATTENDANCELIST_ID BIGINT,
    IS_ATTENDING BOOLEAN,
    FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID),
    FOREIGN KEY (ATTENDANCELIST_ID) REFERENCES ATTENDANCELISTS(ATTENDANCELIST_ID)
);